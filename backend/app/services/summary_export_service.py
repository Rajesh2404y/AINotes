"""
Summary Export Service.
Generates exportable files (PDF and plain TXT) for generated AI summaries.
"""
from __future__ import annotations

import io
import logging
from typing import Any, Dict

logger = logging.getLogger(__name__)


class SummaryExportService:
    """Handles exporting summaries to PDF and plain text formats."""

    @staticmethod
    def export_txt(summary_data: Dict[str, Any], doc_title: str = "Summary Notes") -> str:
        """
        Formats a summary and its extracted metadata into clean, plain-text study notes.
        """
        lines = []
        lines.append("=" * 70)
        lines.append(f"STUDY NOTES: {doc_title.upper()}")
        lines.append("=" * 70)
        lines.append(f"Summary Mode: {summary_data.get('summary_type', 'medium').capitalize()}")
        if summary_data.get("model_name"):
            lines.append(f"AI Engine: {summary_data.get('model_name')}")
        lines.append("")

        lines.append("-" * 50)
        lines.append("SUMMARY CONTENT")
        lines.append("-" * 50)
        lines.append(summary_data.get("summary_text", "").strip())
        lines.append("")

        takeaways = summary_data.get("key_takeaways", [])
        if takeaways:
            lines.append("-" * 50)
            lines.append("KEY TAKEAWAYS")
            lines.append("-" * 50)
            for idx, pt in enumerate(takeaways, start=1):
                lines.append(f"{idx}. {pt}")
            lines.append("")

        definitions = summary_data.get("definitions", [])
        if definitions:
            lines.append("-" * 50)
            lines.append("IMPORTANT DEFINITIONS")
            lines.append("-" * 50)
            for item in definitions:
                if isinstance(item, dict):
                    lines.append(f"* {item.get('term', '')}: {item.get('definition', '')}")
                else:
                    lines.append(f"* {item}")
            lines.append("")

        keywords = summary_data.get("keywords", [])
        if keywords:
            lines.append("-" * 50)
            lines.append("TOPIC KEYWORDS")
            lines.append("-" * 50)
            lines.append(", ".join(keywords))
            lines.append("")

        lines.append("=" * 70)
        lines.append("Generated by AI Notes Summarizer")
        lines.append("=" * 70)

        return "\n".join(lines)

    @staticmethod
    def export_pdf(summary_data: Dict[str, Any], doc_title: str = "Study Notes") -> io.BytesIO:
        """
        Builds a styled PDF document from summary data using ReportLab.
        Returns a BytesIO stream ready for Flask send_file.
        """
        try:
            from reportlab.lib import colors
            from reportlab.lib.pagesizes import letter
            from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
            from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
        except ImportError as e:
            logger.error(f"ReportLab import failed: {e}")
            raise RuntimeError("ReportLab is not installed or available for PDF export.")

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40
        )

        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=20,
            leading=24,
            textColor=colors.HexColor("#1e293b"),
            spaceAfter=4
        )

        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=12
        )

        section_heading = ParagraphStyle(
            "SectionHeading",
            parent=styles["Heading2"],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True
        )

        body_style = ParagraphStyle(
            "SummaryBody",
            parent=styles["BodyText"],
            fontSize=10,
            leading=15,
            textColor=colors.HexColor("#334155"),
            spaceAfter=8
        )

        bullet_style = ParagraphStyle(
            "BulletItem",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#334155"),
            leftIndent=15,
            spaceAfter=4
        )

        story = []

        # Header Title
        story.append(Paragraph(f"Study Notes: {doc_title}", title_style))
        meta_info = f"Mode: {summary_data.get('summary_type', 'medium').capitalize()} | Model: {summary_data.get('model_name', 'AI Engine')}"
        story.append(Paragraph(meta_info, meta_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=12))

        # Summary Section
        story.append(Paragraph("Summary", section_heading))
        summary_paragraphs = summary_data.get("summary_text", "").split("\n\n")
        for para in summary_paragraphs:
            if para.strip():
                # Clean any xml/html-sensitive characters for reportlab
                clean_para = para.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(clean_para, body_style))

        # Key Takeaways Section
        takeaways = summary_data.get("key_takeaways", [])
        if takeaways:
            story.append(Spacer(1, 10))
            story.append(Paragraph("Key Takeaways", section_heading))
            for pt in takeaways:
                clean_pt = str(pt).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(f"&bull;&nbsp;&nbsp;{clean_pt}", bullet_style))

        # Definitions Section
        definitions = summary_data.get("definitions", [])
        if definitions:
            story.append(Spacer(1, 10))
            story.append(Paragraph("Important Definitions", section_heading))
            for item in definitions:
                if isinstance(item, dict):
                    term = item.get("term", "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                    defn = item.get("definition", "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                    defn_html = f"<b>{term}:</b> {defn}"
                else:
                    defn_html = str(item).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(f"&bull;&nbsp;&nbsp;{defn_html}", bullet_style))

        # Keywords Section
        keywords = summary_data.get("keywords", [])
        if keywords:
            story.append(Spacer(1, 10))
            story.append(Paragraph("Topic Keywords", section_heading))
            clean_keywords = ", ".join(keywords).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(clean_keywords, body_style))

        # Footer divider
        story.append(Spacer(1, 16))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#e2e8f0"), spaceAfter=6))
        story.append(Paragraph("Generated by AI Notes Summarizer with Quiz Generation and Translator", meta_style))

        doc.build(story)
        buffer.seek(0)
        return buffer


# Global instance
summary_export_service = SummaryExportService()

